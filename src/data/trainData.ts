/**
 * Searches trains by number, name, or station
 */
export function searchTrains(query: string): TrainInfo[] {
  const clean = query.trim().toLowerCase();
  if (!clean) return POPULAR_TRAINS;

  const matches = POPULAR_TRAINS.filter(
    (t) =>
      t.number.includes(clean) ||
      t.name.toLowerCase().includes(clean) ||
      t.source.toLowerCase().includes(clean) ||
      t.destination.toLowerCase().includes(clean) ||
      t.sourceCode.toLowerCase().includes(clean) ||
      t.destinationCode.toLowerCase().includes(clean)
  );

  // If query is a 4 or 5 digit number and not in existing matches, dynamically synthesize it
  const numericOnly = clean.replace(/\D/g, '');
  if (numericOnly.length >= 4 && !matches.some((m) => m.number === numericOnly)) {
    matches.unshift(generateDynamicTrain(numericOnly));
  }

  return matches;
}

/**
 * Gets a train by exact or fuzzy number, with automatic generator for any 5-digit number
 */
export function getTrainByNumber(number: string): TrainInfo | undefined {
  const clean = number.trim();
  const existing = POPULAR_TRAINS.find((t) => t.number === clean);
  if (existing) return existing;

  const numericOnly = clean.replace(/\D/g, '');
  if (numericOnly.length >= 4) {
    return generateDynamicTrain(numericOnly);
  }

  return POPULAR_TRAINS[0];
}

/**
 * Calculates simulated live running status for a train along its route
 */
export function calculateRunningStatus(
  train: TrainInfo,
  progressOverride?: number
): RunningTrainStatus {
  const stops = train.schedule;
  const progress =
    progressOverride !== undefined
      ? Math.max(0, Math.min(1, progressOverride))
      : 0.42; // default 42% completed journey

  const totalDistance = train.totalDistanceKm;
  const currentDistance = progress * totalDistance;

  // Determine current stop index
  let passedIndex = 0;
  for (let i = 0; i < stops.length; i++) {
    if (stops[i].distanceKm <= currentDistance) {
      passedIndex = i;
    }
  }

  const lastStop = stops[passedIndex];
  const nextStop = stops[Math.min(passedIndex + 1, stops.length - 1)];

  // Interpolate coordinates between lastStop and nextStop
  let currentLat = lastStop.coordinates.lat;
  let currentLng = lastStop.coordinates.lng;

  if (passedIndex < stops.length - 1) {
    const legDistance = nextStop.distanceKm - lastStop.distanceKm;
    const distanceIntoLeg = currentDistance - lastStop.distanceKm;
    const legRatio = legDistance > 0 ? distanceIntoLeg / legDistance : 0;
    currentLat = lastStop.coordinates.lat + (nextStop.coordinates.lat - lastStop.coordinates.lat) * legRatio;
    currentLng = lastStop.coordinates.lng + (nextStop.coordinates.lng - lastStop.coordinates.lng) * legRatio;
  }

  const delayMinutes = passedIndex === 0 ? 0 : 8; // realistic 8 min delay

  const runningStops: TrainStopRunning[] = stops.map((stop, idx) => {
    let status: 'passed' | 'current' | 'upcoming' = 'upcoming';
    if (idx < passedIndex) {
      status = 'passed';
    } else if (idx === passedIndex) {
      status = 'current';
    }

    const stopDelay = idx === 0 ? 0 : delayMinutes;

    return {
      ...stop,
      delayMinutes: stopDelay,
      actualArrival:
        stop.scheduledArrival === 'START'
          ? 'START'
          : addMinutesToTime(stop.scheduledArrival, stopDelay),
      actualDeparture:
        stop.scheduledDeparture === 'END'
          ? 'END'
          : addMinutesToTime(stop.scheduledDeparture, stopDelay),
      status,
    };
  });

  const speed =
    progress >= 0.98 || progress <= 0.02
      ? 0
      : Math.round(train.averageSpeedKmH * (0.9 + Math.sin(progress * 10) * 0.2));

  let statusText = `Approaching ${nextStop.stationName}`;
  if (delayMinutes === 0) {
    statusText += ' • On Time';
  } else {
    statusText += ` • Running Late by ${delayMinutes} min`;
  }

  return {
    trainNumber: train.number,
    trainName: train.name,
    date: 'Today, 06 Nov 2026',
    currentStationCode: lastStop.stationCode,
    lastDepartedStation: `${lastStop.stationName} (${lastStop.stationCode})`,
    nextUpcomingStation: `${nextStop.stationName} (${nextStop.stationCode})`,
    delayMinutes,
    statusText,
    currentSpeedKmH: speed,
    updatedAgoSeconds: 12,
    currentCoordinates: { lat: currentLat, lng: currentLng },
    progressPercent: Math.round(progress * 100),
    stops: runningStops,
  };
}

function addMinutesToTime(timeStr: string, minutes: number): string {
  if (!timeStr || timeStr === 'START' || timeStr === 'END') return timeStr;
  const parts = timeStr.split(':');
  if (parts.length !== 2) return timeStr;
  let totalMin = parseInt(parts[0], 10) * 60 + parseInt(parts[1], 10) + minutes;
  totalMin = (totalMin + 1440) % 1440;
  const h = Math.floor(totalMin / 60);
  const m = totalMin % 60;
  return `${h.toString().padStart(2, '0')}:${m.toString().padStart(2, '0')}`;
}

/**
 * PNR Lookup - returns seeded or procedurally generated valid status
 */
export function lookupPnr(pnr: string): PnrRecord {
  const clean = pnr.replace(/\D/g, '').slice(0, 10);
  if (DEMO_PNR_RECORDS[clean]) {
    return DEMO_PNR_RECORDS[clean];
  }

  // Generate realistic IRCTC PNR result for arbitrary 10-digit number
  const train = POPULAR_TRAINS[parseInt(clean.slice(0, 2), 10) % POPULAR_TRAINS.length];
  const numPassengers = (parseInt(clean.slice(-1), 10) % 3) + 1;
  const isConfirmed = parseInt(clean.slice(-2), 10) % 3 !== 0;

  const passengers = Array.from({ length: numPassengers }).map((_, i) => {
    const coachType = train.classes.includes('3A')
      ? 'B'
      : train.classes.includes('CC')
      ? 'C'
      : 'S';
    const coachNum = (i % 3) + 1;
    const berth = 12 + i * 2;
    const berthTypes: PnrPassenger['berthType'][] = [
      'Lower',
      'Middle',
      'Upper',
      'Side Lower',
      'Side Upper',
      'Window Seat',
    ];
    const berthType = berthTypes[(berth + i) % berthTypes.length];

    return {
      passengerNumber: i + 1,
      name: `Passenger ${i + 1}`,
      age: 26 + i * 8,
      gender: (i % 2 === 0 ? 'M' : 'F') as 'M' | 'F',
      bookingStatus: isConfirmed ? `WL ${12 + i}` : `WL ${24 + i * 3}`,
      currentStatus: isConfirmed
        ? `CNF ${coachType}${coachNum}-${berth} (${berthType.slice(0, 2).toUpperCase()})`
        : `WL ${6 + i * 2}`,
      coach: isConfirmed ? `${coachType}${coachNum}` : '--',
      berthNumber: isConfirmed ? `${berth}` : '--',
      berthType,
      isConfirmed,
    };
  });

  return {
    pnr: clean || '2458913470',
    trainNumber: train.number,
    trainName: train.name,
    doj: '07 Nov 2026',
    fromStation: train.source,
    fromCode: train.sourceCode,
    toStation: train.destination,
    toCode: train.destinationCode,
    boardingStation: `${train.source} (${train.sourceCode})`,
    boardingCode: train.sourceCode,
    travelClass: train.classes[0] || '3A',
    quota: 'GN',
    chartStatus: isConfirmed ? 'Chart Prepared' : 'Chart Not Prepared',
    expectedPlatform: (parseInt(clean.slice(-1), 10) % 8 + 1).toString(),
    confirmationProbabilityPercent: isConfirmed ? 96 : 58,
    farePaid: 1250 * numPassengers,
    passengers,
  };
}

/**
 * Checks seat availability across dates for a train and class
 */
export function checkSeatAvailability(
  trainNumber: string,
  fromCode: string,
  toCode: string,
  baseDate: string,
  travelClass: string,
  quota: string
): SeatAvailabilityResult {
  const train = getTrainByNumber(trainNumber) || POPULAR_TRAINS[0];

  // Base fare calculation based on class and distance
  const baseFares: Record<string, number> = {
    '1A': 2850,
    '2A': 1780,
    '3A': 1260,
    '3E': 1120,
    'CC': 960,
    'EC': 1850,
    'SL': 420,
    '2S': 210,
  };

  const rate = baseFares[travelClass] || 1100;
  const reservationCharge = travelClass === '1A' ? 60 : travelClass === '2A' ? 50 : 40;
  const superfastCharge = 45;
  const tatkalCharge = quota === 'TQ' || quota === 'PT' ? Math.round(rate * 0.3) : 0;
  const gst = Math.round((rate + reservationCharge + superfastCharge + tatkalCharge) * 0.05);
  const totalFare = rate + reservationCharge + superfastCharge + tatkalCharge + gst;

  // Generate 6 upcoming days availability
  const dates: { dateStr: string; label: string }[] = [
    { dateStr: '2026-11-06', label: '06 Nov, Fri' },
    { dateStr: '2026-11-07', label: '07 Nov, Sat' },
    { dateStr: '2026-11-08', label: '08 Nov, Sun' },
    { dateStr: '2026-11-09', label: '09 Nov, Mon' },
    { dateStr: '2026-11-10', label: '10 Nov, Tue' },
    { dateStr: '2026-11-11', label: '11 Nov, Wed' },
  ];

  const days = dates.map((d, index) => {
    // Semi-deterministic realistic availability
    const seed = (parseInt(train.number, 10) + index * 17) % 100;
    if (seed < 45) {
      const seats = 14 + (seed % 48);
      return {
        date: d.label,
        status: 'AVAILABLE' as const,
        count: seats,
        statusLabel: `AVAILABLE - ${seats}`,
        probability: 100,
      };
    } else if (seed < 70) {
      const rac = 4 + (seed % 14);
      return {
        date: d.label,
        status: 'RAC' as const,
        count: rac,
        statusLabel: `RAC ${rac}`,
        probability: 85,
      };
    } else if (seed < 92) {
      const wl = 6 + (seed % 28);
      return {
        date: d.label,
        status: 'WL' as const,
        count: wl,
        statusLabel: `GNWL ${wl}`,
        probability: 60,
      };
    } else {
      return {
        date: d.label,
        status: 'REGRET' as const,
        count: 0,
        statusLabel: 'REGRET / NOT AVAILABLE',
        probability: 10,
      };
    }
  });

  return {
    trainNumber: train.number,
    trainName: train.name,
    fromStation: fromCode,
    toStation: toCode,
    travelClass,
    quota,
    baseFare: rate,
    reservationCharge,
    superfastCharge,
    tatkalCharge,
    gst,
    totalFare,
    days,
  };
}

